import { useSyncExternalStore } from "react";

export type Locale = "zh-CN" | "en";
let locale: Locale = "zh-CN";
try {
  if (localStorage.getItem("frame:locale") === "en") locale = "en";
} catch {
  /* Language switching remains available without local storage. */
}
const listeners = new Set<() => void>();
export const getLocale = () => locale;
export function setLocale(value: Locale) {
  locale = value;
  document.documentElement.lang = value;
  document.title =
    value === "en" ? "FRAME / Creative Studio" : "FRAME / 创作工作室";
  try {
    localStorage.setItem("frame:locale", value);
  } catch {
    /* Preference is retained for this session. */
  }
  listeners.forEach((listener) => listener());
}
export function useLocale() {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    getLocale,
    () => "zh-CN" as Locale,
  );
}
export function t(text: string, ...values: unknown[]): string {
  const translated = locale === "en" ? english[text] || text : text;
  return translated.replace(/\{(\d+)\}/g, (_, index: string) =>
    String(values[Number(index)] ?? ""),
  );
}

